def normalize(text):
    """تطبيع النص للبحث"""
    if not text:
        return ''
    text = text.lower()
    text = re.sub(r'[أإآا]', 'ا', text)
    text = re.sub(r'[ةه]', 'ه', text)
    text = re.sub(r'[يى]', 'ي', text)
    return text

def is_relevant(item):
    title = item.get('title', '')
    category = item.get('category', '')
    source = item.get('source', '')
    
    title_norm = normalize(title)
    cat_norm = normalize(category)
    
    # ── 1. فحص الكلمات السلبية القاطعة في العنوان ──
    for excl in HARD_EXCLUDE_TITLES:
        excl_norm = normalize(excl)
        if excl_norm in title_norm:
            # تحقق: هل يوجد سياق قضائي يُنقذ المادة؟
            has_judicial_context = any(
                normalize(kw) in title_norm 
                for kw in ['قضاء', 'قضائي', 'جناية', 'عقوبة', 'إثبات', 'مرافعة', 'نظام', 'قانون']
            )
            if not has_judicial_context:
                return False
    
    # ── 2. فحص الكلمات الإيجابية ──
    combined = title_norm + ' ' + cat_norm
    for kw in POSITIVE_KEYWORDS:
        if normalize(kw) in combined:
            return True
    
    # ── 3. الأقسام الموثوقة دائماً ──
    TRUSTED_CATEGORIES = [
        'القضاء والأنظمة العامة', 'الأنظمة والتشريعات', 'القضاء الشرعي',
        'الإثبات والشهادة', 'المحاكم والمرافعات', 'أبحاث ودراسات قضائية',
        'القضاء الإداري', 'المحاماة والتحكيم', 'الحسبة والمظالم',
        'المبادئ والقرارات القضائية', 'الأنظمة التجارية',
    ]
    if category in TRUSTED_CATEGORIES:
        # في الأقسام الموثوقة، نقبل المادة إلا إذا كانت مستبعدة صراحةً
        return True
    
    return False

