def normalize(text):
    """تطبيع الهمزات"""
    text = text.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا")
    return text

def is_relevant(item):
    title = item.get("title", "").strip()
    title_norm = normalize(title)
    
    # أولاً: رفض إذا كانت هناك كلمة سلبية
    for neg in NEGATIVE:
        if neg in title or normalize(neg) in title_norm:
            return False
    
    # ثانياً: قبول إذا كانت هناك كلمة إيجابية
    for pos in POSITIVE:
        if pos in title or normalize(pos) in title_norm:
            return True
    
    return False

# تطبيق التصفية
kept = [item for item in items if is_relevant(item)]
removed = [item for item in items if not is_relevant(item)]

print(f"المحتفظ بها: {len(kept)}")
print(f"المحذوفة: {len(removed)}")

