from __future__ import annotations

import re


def normalize(title: str) -> str:
    text = re.sub(r"[أإآا]", "ا", title or "")
    text = re.sub(r"[\u064B-\u065F]", "", text)
    text = re.sub(r"\s+", " ", text)
    return text.strip().lower()


