def intake_decision(title: str) -> str:
    """يعيد CANDIDATE أو REVIEW، ولا يصدر REMOVE أو قبولاً اعتماداً على المصدر."""
    normalized = normalize(title)
    has_direct_scope = any(pattern in normalized for pattern in DIRECT_SCOPE_PATTERNS)
    has_clear_outside = any(pattern in normalized for pattern in CLEAR_OUTSIDE_PATTERNS)
    if has_direct_scope and not has_clear_outside:
        return "CANDIDATE"
    return "REVIEW"
