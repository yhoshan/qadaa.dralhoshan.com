def is_relevant(item):
    title = item.get("title", "")
    category = item.get("category", "")
    source = item.get("source", "")
    
    # إذا كان المصدر قانونياً بحتاً فاقبله مباشرة
    legal_sources = [
        "المكتبة القانونية",
        "مفضلة اللجان شبه القضائية",
        "مجلة قضاء",
        "مجلة الأحكام القضائية",
    ]
    if any(s in source for s in legal_sources):
        # لكن تحقق من الكلمات السلبية أولاً
        for neg in NEGATIVE_KEYWORDS:
            if neg in title:
                return False
        # تحقق من وجود كلمة إيجابية واحدة على الأقل
        for pos in POSITIVE_KEYWORDS:
            if pos in title:
                return True
        # إذا لم تجد كلمة إيجابية، تحقق من التصنيف
        legal_categories = [
            "القضاء والأنظمة العامة", "الأنظمة والتشريعات",
            "المحاكم والمرافعات", "الجنايات والحدود",
            "المحاماة والتحكيم", "القضاء الإداري",
            "الإثبات والشهادة", "الأنظمة التجارية",
            "أنظمة العمل", "أبحاث ودراسات قضائية",
            "المبادئ والقرارات القضائية",
        ]
        return category in legal_categories
    
    # للمصادر الأخرى: تحقق صارم
    # أولاً: رفض إذا كانت هناك كلمة سلبية
    for neg in NEGATIVE_KEYWORDS:
        if neg in title:
            return False
    
    # ثانياً: قبول فقط إذا كانت هناك كلمة إيجابية صريحة
    for pos in POSITIVE_KEYWORDS:
        if pos in title:
            return True
    
    return False

