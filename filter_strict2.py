def is_relevant(item):
    title = item.get('title', '')
    category = item.get('category', '')
    
    title_norm = normalize(title)
    cat_norm = normalize(category)
    
    # الأقسام الموثوقة — مقبول مباشرة
    if category in TRUSTED_CATEGORIES:
        # لكن نستبعد الكلمات القاطعة حتى في الأقسام الموثوقة
        for excl in HARD_EXCLUDE:
            if normalize(excl) in title_norm:
                # هل يوجد سياق قضائي ينقذها؟
                rescue = any(normalize(kw) in title_norm for kw in [
                    'قضاء', 'جنايه', 'عقوبه', 'اثبات', 'مرافعه', 'نظام', 'قانون', 'الحدود', 'القصاص'
                ])
                if not rescue:
                    return False
        return True
    
    # بقية الأقسام — يجب وجود كلمة قضائية في العنوان
    for kw in JUDICIAL_KEYWORDS:
        if normalize(kw) in title_norm:
            return True
    
    return False

