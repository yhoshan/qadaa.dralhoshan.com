all_docs = {}
for query in QUERIES:
    for mediatype in ['texts', 'data']:
        params = urllib.parse.urlencode({
            'q': f'{query} AND mediatype:{mediatype}',
            'output': 'json',
            'rows': 200,
            'start': 0,
            'fl': 'identifier,title,creator,date,subject',
        })
        url = f'https://archive.org/advancedsearch.php?{params}'
        try:
            req = urllib.request.urlopen(url, timeout=15)
            data = json.loads(req.read())
            docs = data['response']['docs']
            for doc in docs:
                iid = doc.get('identifier', '')
                if iid:
                    all_docs[iid] = doc
        except Exception as e:
            print(f'خطأ في {query}: {e}')
        time.sleep(0.25)

print(f'قبل التصفية: {len(all_docs)}')

filtered = []
for iid, doc in all_docs.items():
    raw_title = doc.get('title', '').strip()
    title = clean_title(raw_title)
    if not title or len(title) < 4:
        continue
    if is_dirty(title):
        continue
    if not has_positive(title):
        continue
    arabic_chars = sum(1 for c in title if '\u0600' <= c <= '\u06FF')
    if arabic_chars < len(title) * 0.10:
        continue

    creator = doc.get('creator', '')
    if isinstance(creator, list):
        creator = creator[0] if creator else ''
    date = doc.get('date', '')
    if isinstance(date, list):
        date = date[0] if date else ''

    category = classify(title)
    mat_type = 'مجلة' if any(w in normalize(title) for w in ['مجله', 'دوريه', 'نشره']) else 'كتاب'

    item = {
        'id': f'archive_{iid}',
        'title': title,
        'author': str(creator),
        'investigator': '',
        'publisher': 'أرشيف الإنترنت',
        'year': str(date)[:4] if date else '',
        'link_telegram': '',
        'link_drive': '',
        'link_direct': f'https://archive.org/download/{iid}/{iid}.pdf',
        'source': 'أرشيف الإنترنت',
        'category': category,
        'material_type': mat_type,
        'file_type': 'PDF',
        'file_size': '',
        'pages_count': '',
        'is_featured': False,
        'download_links_count': 1,
    }
    filtered.append(item)

