def is_dirty(title):
    norm = normalize(title)
    for p in DIRTY_EXACT:
        if normalize(p) in norm:
            return True
    # استبعاد أرقام في بداية العنوان مع كلمات إنجليزية
    if re.match(r'^\d{6}\s*[-_]', title.strip()):
        return True
    return False

def clean_title(title):
    # تنظيف عناوين مشوهة
    title = re.sub(r'^\d+\s+[Pp][Dd][Ff]\s+', '', title)
    title = re.sub(r'\s*\.doc\s+[Ff]ile\s+كتاب\s*\d*', '', title)
    title = re.sub(r'\s*[Pp][Dd][Ff]\s+[Ff]ile\s*$', '', title)
    title = re.sub(r'^رسائل قانونية \w+ \d+\s+', '', title)
    title = re.sub(r'\s+رسائل قانونية \w+ \d+\s+', ' ', title)
    return title.strip()

