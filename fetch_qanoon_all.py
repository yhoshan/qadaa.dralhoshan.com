def classify(title):
    norm = normalize(title)
    if any(w in norm for w in ['تحكيم', 'وساطه', 'توفيق', 'تسويه وديه', 'نزاعات تجاريه']):
        return 'التحكيم والوساطة'
    elif any(w in norm for w in ['قانون عقوبات', 'جنايات', 'جرائم', 'جنائي', 'جزائي', 'مخدرات', 'ارهاب', 'سجون', 'حدود', 'قصاص', 'طب شرعي']):
        return 'الجنايات والحدود'
    elif any(w in norm for w in ['مرافعات', 'اجراءات', 'دعوى', 'تقاضي', 'استئناف', 'نقض', 'تمييز', 'اثبات', 'شهاده', 'محكمه ابتدائيه']):
        return 'المحاكم والمرافعات'
