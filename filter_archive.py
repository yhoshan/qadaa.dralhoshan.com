# تحميل النتائج
with open('/home/ubuntu/makanez-qadaa/archive_items.json', 'r', encoding='utf-8') as f:
    items = json.load(f)

print(f"قبل التصفية الصارمة: {len(items)} مادة")

filtered = []
rejected = []

for item in items:
    title = item['title']
    norm_title = normalize(title)
    
    # فحص الكلمات السلبية أولاً
    has_neg = False
    for neg in NEGATIVE_IN_TITLE:
        if normalize(neg) in norm_title:
            has_neg = True
            break
    
    if has_neg:
        rejected.append(f"[سلبي] {title[:60]}")
        continue
    
    # فحص الكلمات الإيجابية — يجب أن يكون في العنوان
    has_pos = False
    for pos in POSITIVE_IN_TITLE:
        if normalize(pos) in norm_title:
            has_pos = True
            break
    
    if not has_pos:
        rejected.append(f"[لا صلة] {title[:60]}")
        continue
    
    # استبعاد العناوين المشبوهة (مجموعات وموسوعات عامة)
    suspicious = ['مجموعة', 'موسوعة', 'مكتبة', 'كتب', 'ملفات', 'أرشيف']
    if any(normalize(s) in norm_title for s in suspicious):
        # قبول فقط إذا كانت مرتبطة بالقضاء صراحةً
        legal_context = ['قانوني', 'قضائي', 'قانون', 'قضاء', 'جنائي']
        if not any(normalize(lc) in norm_title for lc in legal_context):
            rejected.append(f"[مشبوه] {title[:60]}")
            continue
    
    filtered.append(item)

print(f"بعد التصفية الصارمة: {len(filtered)} مادة")
print(f"مرفوض: {len(rejected)} مادة")

# عرض عينة من المقبول
print("\nعينة من المواد المقبولة:")
for item in filtered[:20]:
    print(f"  [{item['category']}] {item['title'][:70]}")

# عرض عينة من المرفوض
print("\nعينة من المرفوض:")
for r in rejected[:15]:
    print(f"  {r}")

