def clean_filename(fn):
    """تنظيف اسم الملف واستخراج العنوان"""
    # إزالة الرقم في البداية
    name = re.sub(r'^[\d\s_-]+', '', fn)
    # إزالة امتداد .cbz
    name = name.replace('.cbz', '')
    # استبدال الشرطات السفلية بمسافات
    name = name.replace('_', ' ')
    # تنظيف المسافات المتعددة
    name = re.sub(r'\s+', ' ', name).strip()
    return name

def matches_positive(fn):
    fn_lower = fn.lower()
    for kw in POSITIVE_KEYWORDS:
        if kw in fn_lower:
            return True
    return False

def matches_negative(fn):
    fn_lower = fn.lower()
    # تحويل اسم الملف المنظّف أيضاً
    title_lower = clean_filename(fn).lower()
    for kw in NEGATIVE_KEYWORDS:
        if kw in fn_lower or kw in title_lower:
            return True
    # استبعاد إضافي بالتعبيرات النمطية
    extra_exclude = [
        r'قضاء\s+عجلون', r'قضاء\s+بيروت', r'قضاء\s+دمشق',
        r'قضاء\s+حلب', r'قضاء\s+حمص', r'قضاء\s+طرابلس',
        r'القضاء\s+والقدر', r'القدر\s+والقضاء',
        r'محاكمة\s+ثورة', r'الخيانة\s+والمحاكمة',
        r'مذكرات\s+المحامية',
        r'اتفاقية\s+القضاء\s+على',
        r'يستحقان\s+اعادة\s+المحاكمة',
    ]
    for pattern in extra_exclude:
        if re.search(pattern, title_lower):
            return True
    return False

def categorize(title):
    """تصنيف المادة بناءً على عنوانها"""
    t = title.lower()
    if any(k in t for k in ['قضاء', 'قاضي', 'قضاة', 'محكمة', 'محاكم', 'قضائي', 'قضائية']):
        return 'القضاء الشرعي'
    if any(k in t for k in ['جنائي', 'جنائية', 'جزائي', 'جزائية', 'عقوبة', 'عقوبات', 'جريمة', 'جرائم', 'حدود', 'قصاص', 'دية']):
        return 'الجنايات والحدود'
    if any(k in t for k in ['قانون', 'قوانين', 'قانوني', 'قانونية', 'تشريع', 'تشريعات']):
        return 'الأنظمة والتشريعات'
    if any(k in t for k in ['نظام الاجراءات', 'نظام المرافعات', 'نظام الاحوال', 'نظام التحكيم', 'نظام الاثبات', 'نظام العمل']):
        return 'الأنظمة والتشريعات'
    if any(k in t for k in ['محاماة', 'محامي', 'محامون']):
        return 'المحاماة والتمثيل القانوني'
    if any(k in t for k in ['مرافعة', 'مرافعات', 'دعوى', 'دعاوى', 'اجراءات', 'تقاضي']):
        return 'المرافعات والإجراءات'
    if any(k in t for k in ['اثبات', 'بينة', 'شهادة', 'شهود', 'اعتراف', 'يمين']):
        return 'الإثبات والشهادات'
    if any(k in t for k in ['طلاق', 'نفقة', 'حضانة', 'ميراث', 'وصية', 'وقف', 'احوال شخصية']):
        return 'الأحوال الشخصية'
    if any(k in t for k in ['عقد', 'عقود', 'بيع', 'ايجار', 'ضمان', 'كفالة', 'رهن', 'معاملات']):
        return 'العقود والمعاملات المالية'
    if any(k in t for k in ['تحكيم', 'وساطة']):
        return 'التحكيم والوساطة'
    if any(k in t for k in ['حسبة', 'مظالم', 'ولاية']):
        return 'الحسبة والمظالم'
    if any(k in t for k in ['فقه مقارن', 'شريعة والقانون', 'فقه والقانون', 'حقوق الانسان']):
        return 'الفقه المقارن والقانون الدولي'
    return 'أبحاث ودراسات قضائية'

